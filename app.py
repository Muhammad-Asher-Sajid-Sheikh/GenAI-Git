def calculator (n1, n2, opr):
    if opr == '+':
        return n1 + n2
    elif opr == '-':
        return n1 - n2
    elif opr == '/':
        return n1 / n2
    elif opr == '*':
        return n1 * n2


print(calculator(1, 2, '+'))